-- ============================================================================
-- Row Level Security (RLS) Configuration (Optional / Recommended)
-- ============================================================================
ALTER TABLE vehicles ENABLE ROW LEVEL SECURITY;
ALTER TABLE rentals ENABLE ROW LEVEL SECURITY;

-- Allow anyone to view vehicles
CREATE POLICY "Public vehicles viewable by everyone" 
    ON vehicles FOR SELECT 
    USING (true);

-- Allow authenticated users or service role to manage vehicles
CREATE POLICY "Enable all access for authenticated users to vehicles" 
    ON vehicles FOR ALL 
    USING (auth.role() = 'authenticated' OR auth.role() = 'service_role')
    WITH CHECK (auth.role() = 'authenticated' OR auth.role() = 'service_role');

-- Allow authenticated users to view their own bookings
CREATE POLICY "Users can view own bookings" 
    ON rentals FOR SELECT 
    USING (auth.uid() = user_id OR auth.role() = 'service_role');

-- Allow authenticated users to insert bookings
CREATE POLICY "Users can insert bookings" 
    ON rentals FOR INSERT 
    WITH CHECK (auth.uid() = user_id OR auth.role() = 'service_role');

-- Allow users to update their own bookings (e.g. cancel)
CREATE POLICY "Users can update own bookings" 
    ON rentals FOR UPDATE 
    USING (auth.uid() = user_id OR auth.role() = 'service_role')
    WITH CHECK (auth.uid() = user_id OR auth.role() = 'service_role');
